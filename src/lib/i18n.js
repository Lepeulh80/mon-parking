export const DICTS = Object.freeze({ fr, en, ar })
export const SOURCE_LANG = 'fr'
export const KEYS = Object.freeze(Object.keys(fr))

/** Traduit une clé. Une clé inconnue renvoie la clé elle-même, jamais du vide. */
export function t(lang, key, vars) {
  const dict = DICTS[lang] || DICTS[SOURCE_LANG]
  let value = dict[key] ?? DICTS[SOURCE_LANG][key] ?? key
  if (vars && typeof vars === 'object') {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replaceAll(`{${name}}`, String(replacement))
    }
  }
  return value
}

/** Clés présentes en français mais absentes (ou vides) dans une langue. */
export function missingKeys(lang) {
  const dict = DICTS[lang]
  if (!dict) return [...KEYS]
  return KEYS.filter((key) => typeof dict[key] !== 'string' || dict[key].trim() === '')
}

/** Clés orphelines : présentes dans une traduction mais absentes de la source. */
export function extraKeys(lang) {
  const dict = DICTS[lang] || {}
  return Object.keys(dict).filter((key) => !(key in DICTS[SOURCE_LANG]))
}

/** Libellé natif de chaque langue, pour le sélecteur. */
export const langOptions = () => LANGS.map(({ code, native }) => ({ value: code, label: native }))
